#!/usr/bin/env node
/* Generates locales/index.ts: static lazy loaders (Metro needs literal require paths). */
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'locales');
const codes = fs
  .readdirSync(dir)
  .filter(f => /^[a-zA-Z-]+\.json$/.test(f))
  .map(f => f.replace('.json', ''))
  .sort((a, b) => (a === 'en' ? -1 : b === 'en' ? 1 : a.localeCompare(b)));
const body = codes
  .map(c => `  '${c}': () => require('./${c}.json') as LocaleResource,`)
  .join('\n');
fs.writeFileSync(
  path.join(dir, 'index.ts'),
  `// AUTO-GENERATED by scripts/generate-locale-index.js - do not edit.\n` +
    `export type LocaleResource = Record<string, unknown>;\n` +
    `export const localeLoaders: Record<string, () => LocaleResource> = {\n${body}\n};\n`,
);
console.log('locales/index.ts:', codes.length, 'locales');
